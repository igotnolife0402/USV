// Parts plugin: shapes, Roblox-style placement, properties, CSG, R6 rig, array, mirror, align, drop.
const SHAPES = ['box', 'sphere', 'cylinder', 'wedge', 'cornerwedge', 'cone', 'torus', 'plane', 'capsule']
export default async function (t) {
  await t.test('insert every shape, stacked on what is under the screen centre', async () => {
    const s = await t.open()
    await s.project('Shapes')
    const ids = []
    for (const sh of SHAPES) ids.push(await s.run('parts.' + sh))
    const objs = await s.eval(ids => ids.map(id => window.studio.app.obj(id)), ids)
    t.eq(objs.map(o => o.shape), SHAPES, 'shapes')
    t.eq(objs.map(o => o.name), ['Part', 'Ball', 'Cylinder', 'Wedge', 'CornerWedge', 'Cone', 'Torus', 'Plane', 'Capsule'], 'Roblox names')
    t.near(objs[0].pos[1], 0.5, 1e-3, 'first part sits on the baseplate')
    t.near(objs[1].pos[1], 2, 1e-3, 'second part stacks on the first')
    await s.idle()
    t.eq(await s.eval(ids => ids.filter(id => window.studio.app.viewport.objects.has(id)).length, ids), 9, 'all drawn')
    s.noErrors()
  })

  await t.test('properties: colour, material, transparency, anchored', async () => {
    const s = await t.open()
    await s.project('Props', { empty: true })
    const id = await s.run('parts.box', { pos: [0, 0.5, 0] })
    await s.run('parts.color', { color: '#3fb950' })
    await s.run('parts.material', { material: 'Neon' })
    await s.run('parts.transparency', { value: 0.5 })
    await s.run('parts.anchor', { value: false })
    const o = await s.eval(id => window.studio.app.obj(id), id)
    t.eq([o.color, o.material, o.transparency, o.anchored], ['#3fb950', 'Neon', 0.5, false])
    const m = await s.eval(id => { const m = window.studio.app.viewport.objects.get(id).material; return [m.transparent, +m.opacity.toFixed(2), m.color.getHexString()] }, id)
    t.eq(m.slice(0, 2), [true, 0.5], 'material is see-through')
    s.noErrors()
  })

  await t.test('faces show from both sides; only a backColor/backTexture part splits front and back', async () => {
    const s = await t.open()
    await s.project('Sides', { empty: true })
    const id = await s.run('parts.box', { pos: [0, 0.5, 0] })
    await s.idle()
    const side = id => window.studio.app.viewport.objects.get(id).material.side
    t.eq(await s.eval(side, id), 2, 'plain part is double-sided, so a flipped face never turns see-through')
    await s.eval(id => window.studio.app.set(id, { texture: 'noise' }), id); await s.idle()
    t.eq(await s.eval(side, id), 2, 'a texture keeps it double-sided')
    await s.eval(id => window.studio.app.set(id, { backColor: '#ff0000' }), id); await s.idle()
    const r = await s.eval(id => { const m = window.studio.app.viewport.objects.get(id), b = m.userData.backMesh; return [m.material.side, b?.material.side, b?.material.color.getHexString(), b?.geometry === m.geometry] }, id)
    t.eq(r, [0, 1, 'ff0000', true], 'backColor: front side + a back mesh on the same geometry in the back colour')
    await s.eval(id => window.studio.app.set(id, { backColor: null }), id); await s.idle()
    t.eq(await s.eval(id => { const m = window.studio.app.viewport.objects.get(id); return [m.material.side, !!m.userData.backMesh, m.children.filter(c => c.name === 'back').length] }, id), [2, false, 0], 'clearing it goes back to one double-sided mesh')
    s.noErrors()
  })

  await t.test('Roblox names, explicit position wins, did-you-mean, Neon glows in its colour, grey dummy', async () => {
    const s = await t.open()
    await s.project('Names')
    const rig = await s.run('parts.rig', {})
    const blk = await s.run('parts.block'), ball = await s.run('parts.ball')
    const at = await s.run('parts.sphere', { position: [-1, 7.2, -1] }), at2 = await s.run('parts.insert', { shape: 'Block', pos: [9, 3, 9], rotation: [0, 90, 0] })
    const o = await s.eval(ids => ids.map(id => window.studio.app.obj(id)), [blk, ball, at, at2])
    t.eq(o.map(x => x.shape), ['box', 'sphere', 'sphere', 'box'], 'parts.block, parts.ball and shape "Block" insert parts')
    t.eq([o[2].pos, o[3].pos, o[3].rot], [[-1, 7.2, -1], [9, 3, 9], [0, 90, 0]], 'position/rotation are used as given, not snapped onto the dummy')
    const err = await s.run('parts.blok').then(() => '', e => e.message)
    t.ok(/Unknown command: parts\.blok \(did you mean .*parts\.block/.test(err), 'unknown command suggests the right one: ' + err)
    t.eq((await s.eval(r => window.studio.app.children(r).map(id => window.studio.app.obj(id).color), rig)).every(c => c === '#a3a2a5'), true, 'dummy parts are #a3a2a5')
    const neon = await s.run('parts.box', { pos: [-6, 1, 4], size: [2, 2, 2], color: '#ff0000', material: 'Neon' })
    await s.eval(() => { const a = window.studio.app; a.select([]); a.viewport.frame(a.ids().filter(i => a.obj(i).name !== 'Baseplate'), 0) })
    const px = await s.eval(ids => { const a = window.studio.app, vp = a.viewport; vp.render(); const gl = vp.renderer.getContext(), r = vp.canvas.getBoundingClientRect()
      return ids.map(id => { const o3 = vp.objects.get(id), w = o3.getWorldPosition(o3.position.clone()), p = vp.project(w), d = new Uint8Array(4)
        gl.readPixels(Math.round((p.x - r.left) * devicePixelRatio), Math.round((r.bottom - p.y) * devicePixelRatio), 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, d); return [...d].slice(0, 3) }) }, [await s.eval(r => window.studio.app.children(r)[0], rig), neon])
    t.log('torso ' + px[0] + ', red neon ' + px[1])
    t.ok(Math.max(...px[0]) - Math.min(...px[0]) <= 10 && px[0][0] > 100, 'dummy renders neutral grey, not purple')
    t.ok(px[1][0] > 230 && px[1][1] < 70 && px[1][2] < 70, 'red Neon renders saturated red, not white')
    s.noErrors()
  })

  await t.test('drag: a part lands on the surface under the pointer and back on the ground', async () => {
    const s = await t.open()
    await s.project('Drag')
    const tower = await s.run('parts.box', { pos: [6, 2, 0], size: [4, 4, 4] })
    const p = await s.run('parts.box', { pos: [-4, 0.5, 0], size: [2, 1, 2] })
    await s.eval(ids => { const a = window.studio.app; a.select([ids[1]]); a.viewport.frame(ids, 0) }, [tower, p])
    await s.idle()
    const scr = (w) => s.eval(w => { const v = window.studio.app.viewport; return v.project(new (v.camera.position.constructor)(...w)) }, w)
    const from = await scr([-4, 0.5, 0]), to = await scr([6, 4, 0]), ground = await scr([-2, 0, 6])
    const drag = async (a, b) => { await s.page.mouse.move(a.x, a.y); await s.page.mouse.down(); await s.page.mouse.move((a.x + b.x) / 2, (a.y + b.y) / 2, { steps: 5 }); await s.page.mouse.move(b.x, b.y, { steps: 5 }); await s.page.mouse.up() }
    await drag(from, to)
    const up = await s.eval(id => window.studio.app.obj(id).pos, p)
    t.log('on the tower ' + JSON.stringify(up))
    t.near(up[1], 4.5, 1e-3, 'rests on the tower top (4 + half its height)')
    t.ok(up[0] >= 4 && up[0] <= 8 && Math.abs(up[2]) <= 2, 'sits over the tower')
    const top = await scr(up)
    await drag(top, ground)
    const down = await s.eval(id => window.studio.app.obj(id).pos, p)
    t.near(down[1], 0.5, 1e-3, 'dragged off, it lands back on the baseplate: ' + JSON.stringify(down))
    await s.run('edit.undo'); t.near(await s.eval(id => window.studio.app.obj(id).pos, p), up, 1e-6, 'one undo per drag')
    s.noErrors()
  })

  await t.test('CSG: union, negate (subtract), intersect', async () => {
    const s = await t.open()
    await s.project('CSG', { empty: true })
    const a = await s.run('parts.box', { pos: [0, 1, 0], size: [4, 2, 2] }), b = await s.run('parts.box', { pos: [2, 1, 0], size: [2, 2, 2] })
    const u = await s.run('csg.union', { ids: [a, b] })
    const uo = await s.eval(id => { const A = window.studio.app; const o = A.obj(id); const g = A.geo.peek(o.geo); return { type: o.type, faces: g.faces.length, n: Object.keys(A.scene.objects).length, pos: o.pos } }, u.id)
    t.eq([uo.type, uo.n], ['mesh', 1], 'union replaces both parts with one mesh')
    t.near(uo.pos, [0.5, 1, 0], 1e-3, 'mesh origin at the bounds centre')
    t.ok(uo.faces >= 6, 'has faces: ' + uo.faces); t.log('union faces', uo.faces)
    const c = await s.run('parts.cylinder', { pos: [0.5, 1, 0], size: [1, 4, 1] })
    await s.run('edit.set', { ids: [c], patch: { negate: true } })
    const h = await s.run('csg.union', { ids: [u.id, c] })
    const ho = await s.eval(id => { const A = window.studio.app; const g = A.geo.peek(A.obj(id).geo); return { faces: g.faces.length, n: Object.keys(A.scene.objects).length } }, h.id)
    t.ok(ho.faces > uo.faces, 'hole adds faces (' + ho.faces + ')'); t.eq(ho.n, 1)
    const x = await s.run('parts.sphere', { pos: [-1.5, 1, 0], size: [3, 3, 3] })
    const i = await s.run('csg.intersect', { ids: [h.id, x] })
    const io = await s.eval(id => { const v = window.studio.app.viewport; const b = v.boxOf([id]); return [b.min.x, b.max.x] }, i.id)
    t.ok(io[0] > -2.01 && io[1] < 0.01, 'intersection lies inside both: x ' + io.map(v => v.toFixed(2)))
    for (let k = 0; k < 3; k++) await s.run('edit.undo') // intersect, sphere insert, hole union
    t.eq(await s.eval(([u, i]) => [window.studio.app.obj(u)?.type, !!window.studio.app.obj(i)], [u.id, i.id]), ['mesh', false], 'undo steps back through the CSG history')
    s.noErrors()
  })

  await t.test('R6 rig, array, mirror, align, drop', async () => {
    const s = await t.open()
    await s.project('Tools')
    const rig = await s.run('parts.rig', { pos: [0, 0, 0] })
    const kids = await s.eval(id => window.studio.app.children(id).map(k => window.studio.app.obj(k).name), rig)
    t.eq(kids.sort(), ['Head', 'Left Arm', 'Left Leg', 'Right Arm', 'Right Leg', 'Torso'], 'R6 parts')
    const b = await s.eval(id => { const x = window.studio.app.viewport.boxOf([id]); return [x.min.y, x.max.y] }, rig)
    t.near(b, [0, 5.2], 0.01, 'rig stands on y = 0, 5.2 studs tall')
    const p = await s.run('parts.box', { pos: [10, 0.5, 0], size: [2, 1, 2] })
    const copies = await s.run('parts.array', { ids: [p], count: 3, offset: [3, 0, 0] })
    t.eq(await s.eval(ids => ids.map(id => window.studio.app.obj(id).pos[0]), copies), [13, 16, 19], 'array offsets')
    const m = await s.run('parts.mirror', { ids: [p], axis: 'x', at: 0 })
    t.near(await s.eval(id => window.studio.app.obj(id).pos, m[0]), [-10, 0.5, 0], 1e-3, 'mirror across x = 0')
    const q = await s.run('parts.box', { pos: [10, 4, 6], size: [2, 1, 2] })
    await s.run('parts.align', { ids: [p, q], axis: 'y', to: 'min' })
    t.near(await s.eval(id => window.studio.app.obj(id).pos[1], q), 0.5, 1e-3, 'align bottoms')
    await s.run('edit.set', { ids: [q], patch: { pos: [10, 7, 0] } })
    await s.run('parts.drop', { ids: [q] })
    t.near(await s.eval(id => window.studio.app.obj(id).pos[1], q), 1.5, 1e-3, 'drop lands on the part below')
    s.noErrors()
  })
}
