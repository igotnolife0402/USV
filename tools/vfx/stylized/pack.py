"""Owner 2026-11-24: 'only save the white ones so it can colour itself' + 'no gif, one way to import all sheets as animation, don't
waste space'. Packs every effect's white frames into shared 1024 atlases (64 cells of 128 px), dropping empty frames and frames
that barely change (they become holds with a longer duration), and writes VFXAtlas.luau: frame table + a player that animates a
BillboardGui ImageLabel via ImageRectOffset and tints it with ImageColor3. ParticleEmitter flipbooks cannot play a sub-range of a
sheet, so packed atlases need this player (or one effect per sheet for emitters).
  python3 pack.py SHEETS_DIR OUTDIR     (SHEETS_DIR = unique.py OUTDIR/action, white Grid4x4 1024 sheets)
  -> OUTDIR/atlas_NN.png, OUTDIR/VFXAtlas.luau, stats"""
import sys, os, glob, re
import numpy as np
from PIL import Image

CELL, GRID, HOLD, EMPTY = 256, 4, 0.006, 0.05
OUT, OG = 128, 8                                  # atlas cells: 64 frames of 128 px per 1024 atlas (256 px cells = 59 uploads for 67 effects)      # HOLD: mean alpha change below this = same picture, keep the earlier frame longer


def frames(path):
    a = np.asarray(Image.open(path).convert('RGBA'))[..., 3]
    return [a[r * CELL:(r + 1) * CELL, c * CELL:(c + 1) * CELL] for r in range(GRID) for c in range(GRID)]


def main(src, out):
    os.makedirs(out, exist_ok=True)
    fs = sorted(f for f in glob.glob(src + '/*.png') if not f.endswith('-color.png'))
    effects, cells, st = [], [], dict(effects=0, frames_in=0, frames_kept=0)
    for f in fs:
        name = re.sub(r'_[a-z]+$', '', os.path.basename(f)[:-4])      # drop the hue: white textures get coloured in game
        fr = frames(f); st['frames_in'] += len(fr); seq = []
        for i, a in enumerate(fr):
            if a.max() / 255 < EMPTY: (seq[-1].__setitem__(1, seq[-1][1] + 1) if seq else None); continue
            if seq and np.abs(np.asarray(Image.fromarray(a).resize((OUT, OUT), Image.LANCZOS), np.float32) - cells[seq[-1][0]]).mean() / 255 < HOLD: seq[-1][1] += 1; continue
            cells.append(np.asarray(Image.fromarray(a).resize((OUT, OUT), Image.LANCZOS), np.float32)); seq.append([len(cells) - 1, 1])
        if seq: effects.append((name, seq))
    per = OG * OG; n_at = (len(cells) + per - 1) // per
    for k in range(n_at):
        at = np.zeros((OG * OUT, OG * OUT), np.uint8)
        for j, c in enumerate(cells[k * per:(k + 1) * per]):
            r, q = divmod(j, OG); at[r * OUT:(r + 1) * OUT, q * OUT:(q + 1) * OUT] = c.astype(np.uint8)
        Image.fromarray(np.dstack([np.full_like(at, 255)] * 3 + [at])).save(f'{out}/atlas_{k:02d}.png', optimize=True)
    rows = []
    for name, seq in effects:
        fr = ', '.join(f'{{{c // per + 1}, {(c % per) % OG * OUT}, {(c % per) // OG * OUT}, {d}}}' for c, d in seq)
        rows.append(f'\t["{name}"] = {{ {fr} }},')
    lua = LUA.replace('%N%', str(n_at)).replace('%ROWS%', '\n'.join(rows)).replace('%CELL%', str(OUT))
    open(f'{out}/VFXAtlas.luau', 'w').write(lua)
    st.update(effects=len(effects), frames_kept=len(cells), atlases=n_at, kb=sum(os.path.getsize(p) for p in glob.glob(out + '/atlas_*.png')) // 1024)
    print(st)


LUA = '''--!strict
-- Generated by tools/vfx/stylized/pack.py. White textures: colour comes from ImageColor3 at play time.
-- Upload atlas_01..%N% as Decals/Images, paste their ids into ATLAS (in order). Never guess ids.
-- Frame = {atlas, x, y, ticks}; one tick = 1/16 of the effect length (held frames have more ticks).
local RunService = game:GetService("RunService")

local VFXAtlas = {}

export type Opts = { color: Color3?, size: number?, duration: number?, light: number? }

local CELL = %CELL%
local TICKS = 16
local ATLAS: { string } = table.create(%N%, "rbxassetid://0") -- TODO: fill with uploaded atlas ids

local FRAMES: { [string]: { { number } } } = {
%ROWS%
}
VFXAtlas.FRAMES = FRAMES
VFXAtlas.ATLAS = ATLAS

function VFXAtlas.names(): { string }
	local out = {}
	for name in FRAMES do
		table.insert(out, name)
	end
	table.sort(out)
	return out
end

-- Plays one effect once on a part/attachment, then cleans up. Returns the BillboardGui.
function VFXAtlas.play(adornee: Instance, name: string, opts: Opts?): BillboardGui?
	local seq = FRAMES[name]
	if not seq then
		warn("VFXAtlas: unknown effect", name)
		return nil
	end
	local o: Opts = opts or {}
	local size = o.size or 6
	local duration = o.duration or 0.6
	local gui = Instance.new("BillboardGui")
	gui.Size = UDim2.fromScale(size, size)
	gui.LightInfluence = 0
	gui.Brightness = o.light or 2
	gui.AlwaysOnTop = false
	gui.Adornee = adornee
	local img = Instance.new("ImageLabel")
	img.BackgroundTransparency = 1
	img.Size = UDim2.fromScale(1, 1)
	img.ImageColor3 = o.color or Color3.new(1, 1, 1)
	img.ImageRectSize = Vector2.new(CELL, CELL)
	img.Parent = gui
	gui.Parent = adornee

	local tickLen = duration / TICKS
	local i, left = 0, 0.0
	local function show(f: { number })
		img.Image = ATLAS[f[1]]
		img.ImageRectOffset = Vector2.new(f[2], f[3])
		left += f[4] * tickLen
	end
	i = 1
	show(seq[1])
	local conn: RBXScriptConnection
	conn = RunService.Heartbeat:Connect(function(dt: number)
		left -= dt
		while left <= 0 do
			i += 1
			if i > #seq then
				conn:Disconnect()
				gui:Destroy()
				return
			end
			show(seq[i])
		end
	end)
	return gui
end

-- Preload every atlas so the first play doesn't flash blank.
function VFXAtlas.preload()
	local ContentProvider = game:GetService("ContentProvider")
	local items = {}
	for _, id in ATLAS do
		local d = Instance.new("Decal")
		d.Texture = id
		table.insert(items, d)
	end
	ContentProvider:PreloadAsync(items)
end

return VFXAtlas
'''

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
