// Writes src/client/WyvernPet/Bake.luau from the same bake the preview and tests use.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TUNE, BODY, TAIL_BLADE } from './spec.mjs';
import { bake, wingAxes } from './motion.mjs';
import { build, WING_PTS, JAW_HINGE } from './geo.mjs';
import { PLAYER_POSE, PLAYER_FLOAT } from './pose.mjs';
import { bakeCamera } from './camera.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const B = bake(), parts = build(), cam = bakeCamera(B);
const f = (v) => (Math.abs(v) < 5e-5 ? '0' : (+v.toFixed(4)).toString());
const arr = (a, per = 12) => { const s = a.map(f), lines = []; for (let i = 0; i < s.length; i += per) lines.push('\t' + s.slice(i, i + per).join(', ') + ','); return '{\n' + lines.join('\n') + '\n}'; };
const v3 = (p) => `Vector3.new(${p.map(f).join(', ')})`;
const flat = (vs) => vs.flat();
const chain = [...BODY.map((b) => [b.name, b.front, b.back]), ['TailBlade', BODY.at(-1).back, BODY.at(-1).back + TAIL_BLADE]];
const axes = (sx) => { const a = wingAxes(WING_PTS, sx); return `{ S = ${v3(a.S)}, E = ${v3(a.E)}, ki = ${v3(a.ki)}, ko = ${v3(a.ko)} }`; };
const tipR = WING_PTS.F1, wR = WING_PTS.W;

const src = `--!strict
-- GENERATED by tools/roblox/wyvern/gen-luau.mjs from spec.mjs (do not edit; change the spec and rerun).
-- Frame: player centre at origin, Y up, +Z = the player's front. Studs, seconds.
local Bake = {}

Bake.LOOP_LEN = ${TUNE.LOOP_LEN}
Bake.NT = ${B.NT}
Bake.DT = ${TUNE.LOOP_LEN} / ${B.NT}
Bake.N = ${B.n}
Bake.L = ${f(B.L)}
Bake.DS = ${f(B.L)} / ${B.n}
Bake.CYCLES = ${B.cycles}
Bake.SWAY_CYCLES = 8
Bake.BODY_LEN = ${f(BODY.at(-1).back + TAIL_BLADE)}

-- per-stud path samples (closed): position, up, tangent, then channels
Bake.P = ${arr(flat(B.P))}
Bake.UP = ${arr(flat(B.up))}
Bake.TAN = ${arr(flat(B.tan))}
Bake.DASH = ${arr(B.dash)}
Bake.FLARE = ${arr(B.flare)}
Bake.FOLD = ${arr(B.fold)}
Bake.SPREAD = ${arr(B.spread)}
Bake.GLIDE = ${arr(B.glideW)}
Bake.MOVE = ${arr(B.tags, 30)}
Bake.MOVE_NAMES = { ${B.moves.map((m) => `"${m}"`).join(', ')} }

-- per-time samples (NT + 1 over one loop)
Bake.S_OF_T = ${arr(B.sOfT)}
Bake.PHASE = ${arr(B.phase)}

-- body chain nose -> tail: { name, front, back } (distance from the nose along the path)
Bake.CHAIN = {
${chain.map(([n, a, b]) => `\t{ name = "${n}", front = ${f(a)}, back = ${f(b)} },`).join('\n')}
}

-- every mesh part: anchor frame, mesh bounding-box centre in that frame, size (sets MeshPart.Size)
Bake.PARTS = {
${parts.map((p) => `\t{ name = "${p.name}", anchor = "${p.anchor}", mat = "${p.mat}", center = ${v3(p.center)}, size = ${v3(p.size)} },`).join('\n')}
}

-- wings: inner flaps about S->ki, outer folds about E->ko (TorsoSeg2 frame); + lifts the wrist
Bake.WING = { R = ${axes(1)}, L = ${axes(-1)} }
Bake.WING_TIP = { R = { tip = ${v3(tipR)}, wrist = ${v3(wR)} }, L = { tip = ${v3([-tipR[0], tipR[1], tipR[2]])}, wrist = ${v3([-wR[0], wR[1], wR[2]])} } }
Bake.JAW_HINGE = ${v3(JAW_HINGE)}

-- cinematic camera, per clock sample (NT + 1): story time warp (linear lookup), camera pos/look (Catmull-Rom), fov,
-- flash (-1 black .. 1 white, linear) and shake amplitude in studs (linear). Payoff = hit-stop at the flare.
Bake.CAM = {
	WARP = ${arr(cam.warp)},
	POS = ${arr(flat(cam.pos))},
	LOOK = ${arr(flat(cam.look))},
	FOV = ${arr(cam.fov)},
	FLASH = ${arr(cam.flash)},
	SHAKE = ${arr(cam.shake)},
	FOCUS = ${v3(cam.focus)},
	PAYOFF_CLOCK = ${f(cam.cF)},
	PAYOFF_STORY = ${f(cam.tPay)},
}

Bake.PLAYER_POSE = {
${Object.entries(PLAYER_POSE).map(([k, a]) => `\t${k} = { ${a.join(', ')} },`).join('\n')}
}
Bake.PLAYER_FLOAT = { height = ${PLAYER_FLOAT.height}, bob = ${PLAYER_FLOAT.bob}, bobPeriod = ${PLAYER_FLOAT.bobPeriod} }

return Bake
`;
const out = path.join(here, 'src', 'client', 'WyvernPet', 'Bake.luau');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log(`Bake.luau ${(src.length / 1024).toFixed(0)} KB, ${B.n} path samples, ${B.NT + 1} time samples, ${parts.length} parts`);
