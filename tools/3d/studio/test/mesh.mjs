// Mesh plugin: primitives, edit mode, selection, every op, modal extrude, knife tool, undo, store, screenshots.
const PRIMS = { cube: 6, uvsphere: 128, icosphere: 80, cylinder: 18, cone: 17, torus: 288, plane: 1, grid: 64 }
// geo summary of an object: id, faces, verts, signed volume, bbox
const G = (s, id) => s.eval(id => {
  const A = window.studio.app, o = A.obj(id), g = A.geo.peek(o.geo), v = g.verts
  let vol = 0
  for (const f of g.faces) for (let k = 1; k + 1 < f.length; k++) {
    const [a, b, c] = [f[0], f[k], f[k + 1]].map(i => [v[i * 3], v[i * 3 + 1], v[i * 3 + 2]])
    vol += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
  }
  const lo = [1e9, 1e9, 1e9], hi = [-1e9, -1e9, -1e9]
  for (let i = 0; i < v.length; i++) { lo[i % 3] = Math.min(lo[i % 3], v[i]); hi[i % 3] = Math.max(hi[i % 3], v[i]) }
  const he = new Set(); for (const f of g.faces) f.forEach((a, k) => he.add(a + ',' + f[(k + 1) % f.length]))
  const open = [...he].filter(k => !he.has(k.split(',').reverse().join(','))).length
  return { open, geo: o.geo, faces: g.faces.length, verts: v.length / 3, vol: +vol.toFixed(3), size: hi.map((x, i) => +(x - lo[i]).toFixed(3)), f: g.faces, v: [...v] }
}, id)
// project local mesh points of object id to client pixels
const P = (s, id, pts) => s.eval(([id, pts]) => {
  const A = window.studio.app, vp = A.viewport, m = A.worldMatrix(id)
  return pts.map(p => { const q = vp.project(vp.camera.position.clone().set(...p).applyMatrix4(m)); return [q.x, q.y] })
}, [id, pts])
const edgesOf = g => { const s = new Map(); for (const f of g.f) f.forEach((a, k) => { const b = f[(k + 1) % f.length]; s.set(Math.min(a, b) + ',' + Math.max(a, b), [a, b]) }); return [...s.values()] }

export default async function (t) {
  await t.test('primitives: face counts and segment parameters', async () => {
    const s = await t.open()
    await s.project('Prims', { empty: true })
    let x = -12
    for (const [k, n] of Object.entries(PRIMS)) { const id = await s.run('mesh.' + k, { pos: [x += 3, 1, 0] }); t.eq((await G(s, id)).faces, n, k) }
    t.eq((await G(s, await s.run('mesh.cylinder', { seg: 8 }))).faces, 10, 'cylinder seg 8')
    t.eq((await G(s, await s.run('mesh.grid', { seg: 4 }))).faces, 16, 'grid seg 4')
    t.eq((await G(s, await s.run('mesh.cube', { seg: 2 }))).faces, 24, 'cube seg 2')
    t.eq((await G(s, await s.run('mesh.uvsphere', { seg: 8, rings: 4 }))).faces, 32, 'uv sphere 8x4')
    t.eq((await G(s, await s.run('mesh.icosphere', { sub: 2 }))).faces, 320, 'ico sphere sub 2')
    t.eq((await G(s, await s.run('mesh.torus', { seg: 8, tubeSeg: 6 }))).faces, 48, 'torus 8x6')
    const loose = await s.eval(() => window.studio.commands().filter(c => c.id.startsWith('mesh.') && !c.menu && !['mesh.select', 'mesh.transform'].includes(c.id)).map(c => c.id))
    t.eq(loose, [], 'every mesh command is in a menu')
    s.noErrors()
  })

  await t.test('edit mode: Tab in and out, parts convert, overlay drawn', async () => {
    const s = await t.open()
    await s.project('Edit', { empty: true })
    const id = await s.run('mesh.cube', { pos: [0, 1, 0] })
    await s.eval(id => window.studio.select([id]), id)
    await s.page.keyboard.press('Tab')
    t.eq(await s.eval(() => window.studio.app.mode), 'mesh', 'Tab enters edit mode')
    await s.idle()
    const pts = await s.eval(() => { let n = 0, l = 0; window.studio.app.viewport.helpers.traverse(o => { if (o.isPoints) n++; if (o.isLineSegments) l++ }); return [n, l] })
    t.ok(pts[0] >= 1 && pts[1] >= 1, 'verts as points and edges as lines: ' + pts)
    await s.page.keyboard.press('Tab')
    t.eq(await s.eval(() => window.studio.app.mode), 'build', 'Tab exits')
    const p = await s.run('parts.box', { pos: [4, 0.5, 0] })
    await s.run('mesh.edit', { id: p })
    const o = await s.eval(p => { const A = window.studio.app; return { mode: A.mode, type: A.obj(p).type, sel: A.selection } }, p)
    t.eq([o.mode, o.type, o.sel], ['mesh', 'mesh', [p]], 'part became a mesh in edit mode')
    t.eq((await G(s, p)).faces, 6, 'box has 6 faces')
    s.noErrors()
  })

  await t.test('ops change the geo as expected', async () => {
    const s = await t.open()
    await s.project('Ops', { empty: true })
    let x = -20
    const cube = () => s.run('mesh.cube', { pos: [x += 3, 1, 0] })
    let id = await cube(); const g0 = await G(s, id)
    t.eq([g0.faces, g0.verts, g0.vol], [6, 8, 8], 'cube')
    let r = await s.run('mesh.extrude', { id, faces: [0], dist: 1 }); let g = await G(s, id)
    t.eq([r.faces, g.faces, g.verts, g.vol, g.open], [10, 10, 12, 12, 0], 'extrude: 6 -> 10 faces, volume +4, still closed')
    t.eq(g.size.slice().sort(), [2, 2, 3], 'extrude grew one side by 1')
    id = await cube(); await s.run('mesh.inset', { id, faces: [0], amount: 0.3 }); g = await G(s, id)
    t.eq([g.faces, g.verts], [10, 12], 'inset')
    id = await cube(); g = await G(s, id); const e0 = edgesOf(g)[0]
    await s.run('mesh.bevel', { id, edges: [e0], width: 0.2, segments: 1 }); g = await G(s, id)
    t.eq([g.faces, g.verts], [7, 10], 'bevel one edge')
    id = await cube(); g = await G(s, id)
    await s.run('mesh.bevel', { id, edges: edgesOf(g), width: 0.2, segments: 1 }); g = await G(s, id)
    t.eq(g.faces, 26, 'bevel all edges')
    id = await cube(); g = await G(s, id)
    await s.run('mesh.bevel', { id, edges: [edgesOf(g)[0]], width: 0.3, segments: 3 }); g = await G(s, id); t.eq([g.faces, g.verts], [11, 14], 'bevel 3 segments: 3 strips + 2 corner fills'); t.ok(g.vol < 8 && g.vol > 7.9, 'bevel volume ' + g.vol)
    id = await cube(); g = await G(s, id)
    await s.run('mesh.loopcut', { id, edge: edgesOf(g)[0], cuts: 1 }); t.eq((await G(s, id)).faces, 10, 'loop cut')
    id = await cube(); await s.run('mesh.loopcut', { id, edge: edgesOf(g)[0], cuts: 2 }); t.eq((await G(s, id)).faces, 14, 'loop cut x2')
    id = await cube(); await s.run('mesh.subdivide', { id }); g = await G(s, id)
    t.eq([g.faces, g.verts, g.vol], [24, 26, 8], 'subdivide keeps the shape')
    id = await cube(); await s.run('mesh.smooth', { id, level: 1 }); g = await G(s, id)
    t.eq([g.faces, g.verts], [24, 26], 'smooth level 1'); t.ok(g.vol < 8 && g.vol > 3, 'smooth rounds the cube: vol ' + g.vol)
    id = await cube(); await s.run('mesh.smooth', { id, level: 2 }); t.eq((await G(s, id)).faces, 96, 'smooth level 2')
    id = await cube(); g = await G(s, id)
    await s.run('mesh.mergeCenter', { id, verts: g.f[0] }); g = await G(s, id)
    t.eq([g.faces, g.verts], [5, 5], 'merge at center')
    id = await cube(); await s.run('mesh.extrude', { id, faces: [0], dist: 0 }); t.eq((await G(s, id)).verts, 12, 'zero extrude doubles verts')
    r = await s.run('mesh.mergeDist', { id, dist: 0.001, verts: [...Array(12).keys()] }); g = await G(s, id)
    t.eq([r.removed, g.verts, g.faces], [4, 8, 6], 'merge by distance')
    id = await cube(); g = await G(s, id); const loop = g.f[0]
    await s.run('mesh.delete', { id, what: 'face', faces: [0] }); g = await G(s, id)
    t.eq([g.faces, g.verts, g.open], [5, 8, 4], 'delete face leaves a 4-edge hole')
    await s.run('mesh.fill', { id, verts: loop }); g = await G(s, id)
    t.eq([g.faces, g.vol, g.open], [6, 8, 0], 'fill closes the hole')
    await s.run('mesh.delete', { id, what: 'vert', verts: [0] }); g = await G(s, id)
    t.eq([g.faces, g.verts], [3, 7], 'delete vertex')
    id = await cube(); g = await G(s, id)
    await s.run('mesh.delete', { id, what: 'edge', edges: [edgesOf(g)[0]] }); t.eq((await G(s, id)).faces, 4, 'delete edge')
    id = await cube(); await s.run('mesh.flip', { id }); t.eq((await G(s, id)).vol, -8, 'flip')
    await s.run('mesh.recalc', { id }); t.eq((await G(s, id)).vol, 8, 'recalculate outward')
    await s.run('mesh.shadeSmooth', { id }); t.eq(await s.eval(id => window.studio.app.obj(id).smooth, id), true, 'shade smooth')
    await s.run('mesh.shadeFlat', { id }); t.eq(await s.eval(id => window.studio.app.obj(id).smooth, id), false, 'shade flat')
    id = await cube(); r = await s.run('mesh.knife', { id, points: [[-1, 1, 0], [1, 1, 0]] }); g = await G(s, id)
    t.eq([r.cut, g.faces, g.verts, g.vol], [1, 7, 10, 8], 'knife across the top face')
    id = await cube(); g = await G(s, id)
    const vi = [0, 1, 2, 3, 4, 5, 6, 7].find(i => g.v[i * 3] > 0.5), mi = [0, 1, 2, 3, 4, 5, 6, 7].find(i => Math.abs(g.v[i * 3] + g.v[vi * 3]) < 1e-6 && Math.abs(g.v[i * 3 + 1] - g.v[vi * 3 + 1]) < 1e-6 && Math.abs(g.v[i * 3 + 2] - g.v[vi * 3 + 2]) < 1e-6)
    await s.run('mesh.mirrorX', { id, on: true })
    await s.run('mesh.transform', { id, verts: [vi], move: [0.5, 0, 0] }); g = await G(s, id)
    t.near([g.v[vi * 3], g.v[mi * 3]], [1.5, -1.5], 1e-6, 'mirror X moves the twin')
    await s.run('mesh.mirrorX', { id, on: false })
    await s.run('mesh.transform', { id, verts: [vi], move: [0.5, 0, 0] }); g = await G(s, id)
    t.near([g.v[vi * 3], g.v[mi * 3]], [2, -1.5], 1e-6, 'mirror off')
    await s.run('mesh.transform', { id, verts: [0, 1, 2, 3, 4, 5, 6, 7], scale: 2, center: [0, 0, 0] }); t.ok((await G(s, id)).size[1] === 4, 'scale')
    s.noErrors()
  })

  await t.test('selection: modes, all, linked, click, shift-click and box select', async () => {
    const s = await t.open()
    await s.project('Sel', { empty: true })
    const id = await s.run('mesh.cube', { pos: [0, 1, 0] })
    await s.run('mesh.edit', { id })
    await s.eval(id => window.studio.app.viewport.frame([id], 0), id); await s.idle()
    t.eq(await s.eval(() => window.studio.app.tool), 'mesh-select', 'select tool mapped')
    await s.run('mesh.selFace')
    t.eq(await s.run('mesh.selectAll'), 6, 'select all faces')
    t.eq(await s.run('mesh.deselectAll'), 0, 'deselect all')
    await s.run('mesh.select', { faces: [0] })
    t.eq(await s.run('mesh.selectLinked'), 6, 'select linked')
    await s.page.keyboard.press('1'); t.eq(await s.run('mesh.selectAll'), 8, 'key 1 = vertex mode, A selects 8')
    await s.page.keyboard.press('2'); t.eq(await s.run('mesh.selectAll'), 12, 'key 2 = edge mode')
    await s.page.keyboard.press('3'); await s.run('mesh.deselectAll')
    const g = await G(s, id), top = g.f.findIndex(f => f.every(i => g.v[i * 3 + 1] > 0.9))
    const [c] = await P(s, id, [[0, 1, 0]])
    await s.page.mouse.click(c[0], c[1])
    t.eq(await s.run('mesh.select', { add: true }), [top], 'click picks the top face')
    const side = g.f.findIndex((f, i) => i !== top && f.every(k => g.v[k * 3 + 2] > 0.9)), sc = g.f[side].reduce((p, k) => p.map((x, j) => x + g.v[k * 3 + j] / 4), [0, 0, 0])
    const [d] = await P(s, id, [sc])
    await s.page.keyboard.down('Shift'); await s.page.mouse.click(d[0], d[1]); await s.page.keyboard.up('Shift')
    t.eq((await s.run('mesh.select', { add: true })).sort(), [top, side].sort(), 'shift-click adds')
    await s.page.keyboard.press('1')
    const sp = await P(s, id, [...Array(8).keys()].map(i => g.v.slice(i * 3, i * 3 + 3))), xs = sp.map(p => p[0]), ys = sp.map(p => p[1])
    const x0 = Math.min(...xs) - 12, y0 = Math.min(...ys) - 12, x1 = Math.max(...xs) + 12, y1 = Math.max(...ys) + 12
    await s.page.mouse.move(x0, y0); await s.page.mouse.down()
    await s.page.mouse.move((x0 + x1) / 2, (y0 + y1) / 2, { steps: 4 }); await s.page.mouse.move(x1, y1, { steps: 4 }); await s.page.mouse.up()
    const boxed = await s.run('mesh.select', { add: true })
    t.eq(boxed.length, 7, 'box select takes the 7 visible corners, not the hidden one')
    s.noErrors()
  })

  await t.test('modal extrude (E, move, click) and knife tool (K, clicks, Enter)', async () => {
    const s = await t.open()
    await s.project('Modal', { empty: true })
    const id = await s.run('mesh.cube', { pos: [0, 1, 0] })
    await s.run('mesh.edit', { id })
    await s.eval(id => window.studio.app.viewport.frame([id], 0), id); await s.idle()
    let g = await G(s, id); const top = g.f.findIndex(f => f.every(i => g.v[i * 3 + 1] > 0.9))
    await s.run('mesh.select', { faces: [top] })
    const [c] = await P(s, id, [[0, 1, 0]])
    await s.page.mouse.move(c[0], c[1]); await s.page.keyboard.press('E')
    t.ok(await s.eval(() => !!document.querySelector('.mesh-hint')), 'hint shows')
    await s.page.mouse.move(c[0], c[1] - 40, { steps: 3 }); await s.page.mouse.move(c[0], c[1] - 80, { steps: 3 })
    await s.page.mouse.click(c[0], c[1] - 80)
    g = await G(s, id)
    t.eq(g.faces, 10, 'modal extrude added 4 faces')
    t.ok(g.size[1] > 2.2, 'top face rose: height ' + g.size[1])
    const before = g.faces
    await s.run('edit.undo'); t.eq((await G(s, id)).faces, 6, 'one undo removes the drag extrude')
    await s.page.keyboard.press('K')
    t.eq(await s.eval(() => window.studio.app.tool), 'mesh-knife', 'K picks the knife')
    const [a, b] = await P(s, id, [[-0.999, 1, 0], [0.999, 1, 0]])
    await s.page.mouse.click(a[0], a[1]); await s.page.mouse.click(b[0], b[1])
    await s.page.keyboard.press('Enter')
    g = await G(s, id)
    t.eq([g.faces, g.vol], [7, 8], 'knife tool cut the top face in two (was ' + before + ')')
    s.noErrors()
  })

  await t.test('undo restores the geo; the geo is saved to the store', async () => {
    const s = await t.open()
    const pid = await s.project('Undo', { empty: true })
    const id = await s.run('mesh.cube', { pos: [0, 1, 0] })
    const g0 = await G(s, id)
    await s.run('mesh.extrude', { id, faces: [0], dist: 1 })
    await s.run('mesh.inset', { id, faces: [0] })
    const g2 = await G(s, id)
    t.eq(g2.faces, 14, 'extrude then inset')
    await s.run('edit.undo'); t.eq((await G(s, id)).faces, 10, 'undo inset')
    await s.run('edit.undo'); const g1 = await G(s, id)
    t.eq([g1.geo, g1.faces], [g0.geo, 6], 'undo extrude: original geo back')
    await s.run('edit.redo'); await s.run('edit.redo'); t.eq((await G(s, id)).geo, g2.geo, 'redo')
    await s.run('mesh.edit', { id }); t.eq(await s.eval(() => window.studio.app.mode), 'mesh')
    await s.run('mesh.subdivide', { id }); const g3 = await G(s, id)
    await s.run('edit.undo'); t.eq((await G(s, id)).geo, g2.geo, 'undo inside edit mode')
    await s.run('edit.redo')
    await s.eval(() => window.studio.app.store.flush())
    const path = 'projects/' + pid + '/geo/' + g3.geo
    await s.waitFor(p => !!window.__mock.get(p), path)
    const saved = await s.eval(p => window.__mock.get(p), path)
    t.eq([saved.faces.length, saved.verts.length / 3], [g3.faces, g3.verts], 'saved geo matches')
    s.noErrors()
  })

  for (const device of ['desktop', 'phone']) {
    await t.test('screenshot ' + device, async () => {
      const s = await t.open({ device })
      await s.project('Shot', { empty: true })
      const id = await s.run('mesh.cube', { pos: [0, 1, 0], seg: 2 })
      await s.run('mesh.edit', { id })
      await s.run('mesh.extrude', { id, faces: [0], dist: 0.6 })
      await s.run('mesh.selFace')
      const g = await G(s, id), top = g.f.map((f, i) => [i, f]).filter(([, f]) => f.every(k => g.v[k * 3 + 1] > 0.9)).map(([i]) => i)
      await s.run('mesh.select', { faces: top.length ? top : [0] })
      await s.eval(id => window.studio.app.viewport.frame([id], 0), id); await s.idle()
      if (device === 'desktop') t.ok(await s.eval(() => !!document.querySelector('.mesh-ops button')), 'mesh panel with op buttons')
      t.ok(await s.eval(() => document.documentElement.scrollWidth <= innerWidth), 'no sideways scroll')
      await s.shot(device + '-mesh.png')
      s.noErrors()
    })
  }
}
